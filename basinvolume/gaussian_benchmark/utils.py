class LineStitcher(object):
    
    def __init__(self, raw_lines):
        self.raw_lines = raw_lines
        self.lines = []
        self.stitch_lines()
    
    def stitch_lines(self):
        skip = True
        self.open_count = 0
        self.closed_count = 0
        for l in self.raw_lines:
            if not skip:
                if l in ['\n', '\r\n']:
                    skip = True
                    break
                for c in l:
                    self.process_character(c)
            if l.startswith("Means:"):
                skip = False
    
    def process_character(self, c):
        close_line = False
        if c == "[":
            self.open_count += 1
            if self.open_count == 1:
                self.open_new_line()
            elif self.open_count > 2:
                raise Exception("illegal open count")
        elif c == "]":
            self.closed_count += 1
            if self.closed_count == 2:
                close_line = True
            elif self.closed_count > 2:
                raise Exception("illegal closed count")
        self.add_char_to_current_line(c)
        if close_line:
            self.close_current_line()
    
    def open_new_line(self):
        self.current_line = str()
        
    def close_current_line(self):
        self.lines.append(self.current_line)
        self.open_count = 0
        self.closed_count = 0
        
    def add_char_to_current_line(self, c):
        if c in ["\n", "\t"]:
            return
        self.current_line += c
        if self.closed_count == 1 and self.open_count == 1 and not self.current_line.endswith("\t"):
            self.current_line += "\t"

